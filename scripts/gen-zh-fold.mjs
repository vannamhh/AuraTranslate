#!/usr/bin/env node
/**
 * Regenerates `src-tauri/src/core/matching/zh_fold.txt`, the Traditional/Simplified fold table
 * used by `core::matching::find_terms`. Needs the `sqlite3` CLI on PATH.
 *
 * Usage: node scripts/gen-zh-fold.mjs [--db <dict-core.db>] [--out <zh_fold.txt>]
 */
import { execFileSync } from 'node:child_process'
import { writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const REPO_ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const SOURCES = ['unihan', 'cc-cedict', 'cvdict']

const options = {
  db: join(REPO_ROOT, 'src-tauri', 'resources', 'dict', 'dict-core.db'),
  out: join(REPO_ROOT, 'src-tauri', 'src', 'core', 'matching', 'zh_fold.txt'),
}
const args = process.argv.slice(2)
for (let i = 0; i < args.length; i += 2) {
  if ((args[i] !== '--db' && args[i] !== '--out') || args[i + 1] === undefined) {
    console.error(`unknown or incomplete argument '${args[i]}'. Usage: gen-zh-fold.mjs [--db <path>] [--out <path>]`)
    process.exit(1)
  }
  options[args[i].slice(2)] = resolve(args[i + 1])
}

const inList = SOURCES.map((s) => `'${s}'`).join(',')
const sql =
  `SELECT e.headword || char(9) || e.headword_simp FROM dict_entry e JOIN dict_source s ON s.id = e.source_id ` +
  `WHERE s.code IN (${inList}) AND e.headword_simp IS NOT NULL AND e.headword_simp <> e.headword`

let raw
try {
  raw = execFileSync('sqlite3', ['-readonly', options.db, sql], { encoding: 'utf8', maxBuffer: 1 << 28 })
} catch (error) {
  console.error(`gen-zh-fold: cannot read ${options.db}: ${error.message}\nThis is an infrastructure failure, not a pass.`)
  process.exit(1)
}

let versions
try {
  versions = execFileSync(
    'sqlite3',
    ['-readonly', options.db, `SELECT code || ' ' || source_version FROM dict_source WHERE code IN (${inList}) ORDER BY code`],
    { encoding: 'utf8' },
  )
    .split('\n')
    .filter((line) => line !== '')
} catch (error) {
  console.error(`gen-zh-fold: cannot read source versions: ${error.message}\nThis is an infrastructure failure, not a pass.`)
  process.exit(1)
}
if (versions.length !== SOURCES.length) {
  console.error(`gen-zh-fold: expected ${SOURCES.length} source versions, got ${versions.length}; this is an infrastructure failure, not a pass.`)
  process.exit(1)
}

const inRange = (ch) => {
  const cp = ch.codePointAt(0)
  return cp >= 0x3400 && cp <= 0xffff
}

const parent = new Map()
const find = (x) => {
  let root = x
  while (parent.get(root) !== root) root = parent.get(root)
  while (parent.get(x) !== root) {
    const next = parent.get(x)
    parent.set(x, root)
    x = next
  }
  return root
}
const add = (x) => {
  if (!parent.has(x)) parent.set(x, x)
}

let pairs = 0
for (const line of raw.split('\n')) {
  if (line === '') continue
  const [trad, simp] = line.split('\t')
  const a = Array.from(trad ?? '')
  const b = Array.from(simp ?? '')
  if (a.length !== 1 || b.length !== 1 || !inRange(a[0]) || !inRange(b[0])) continue
  add(a[0])
  add(b[0])
  const ra = find(a[0])
  const rb = find(b[0])
  if (ra !== rb) {
    if (ra.codePointAt(0) < rb.codePointAt(0)) parent.set(rb, ra)
    else parent.set(ra, rb)
  }
  pairs += 1
}

if (pairs === 0) {
  console.error('gen-zh-fold: no pairs read; this is an infrastructure failure, not a pass.')
  process.exit(1)
}

const rows = [...parent.keys()]
  .map((ch) => [ch, find(ch)])
  .filter(([ch, rep]) => ch !== rep)
  .sort((x, y) => x[0].codePointAt(0) - y[0].codePointAt(0))

const header = [
  '# Traditional/Simplified fold table: each line is `<char>\\t<representative of its class>`.',
  `# Source: single-character headword/headword_simp pairs of ${SOURCES.join(', ')} in dict-core.db,`,
  '# restricted to U+3400..U+FFFF (3-byte UTF-8), merged into equivalence classes, representative = smallest code point.',
  `# Source versions: ${versions.join('; ')}.`,
  '# Licences: CC-BY-SA-4.0 (cc-cedict, cvdict), Unicode-3.0 (unihan). Attribution in NOTICE.txt.',
  '# Generated by `node scripts/gen-zh-fold.mjs`; do not edit by hand.',
]
writeFileSync(options.out, header.join('\n') + '\n' + rows.map(([c, r]) => `${c}\t${r}`).join('\n') + '\n')
console.log(`wrote ${rows.length} fold entries to ${options.out}`)
